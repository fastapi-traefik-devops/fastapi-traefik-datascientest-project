#!/usr/bin/env python3
"""Convert a CustomResourceDefinition into a strict kubeconform JSON schema (offline).

Usage: kubectl get crd NAME -o json > crd.json; python3 ci/crd_schema.py crd.json VERSION
writes ci/crd-<group>-<kind>-<version>.json, the name ci/validate.sh looks up for that kind.
"""
import argparse
import hashlib
import json
from pathlib import Path

FREE_FORM = ('x-kubernetes-preserve-unknown-fields', 'x-kubernetes-embedded-resource')


def strict(node):
    # Same rules as kubeconform's openapi2jsonschema in strict mode, without descriptions.
    if isinstance(node, list):
        return [strict(item) for item in node]
    if not isinstance(node, dict):
        return node
    result = {key: strict(value) for key, value in node.items() if key != 'description'}
    if result.pop('nullable', False) and isinstance(result.get('type'), str):
        result['type'] = [result['type'], 'null']
    if result.get('x-kubernetes-int-or-string'):
        result.setdefault('anyOf', [{'type': 'integer'}, {'type': 'string'}])
    if ('properties' in node and 'additionalProperties' not in node
            and not any(node.get(flag) for flag in FREE_FORM)):
        result['additionalProperties'] = False
    return result


def convert(crd, version):
    spec = crd['spec']
    matches = [v for v in spec['versions'] if v['name'] == version and v.get('served')]
    if len(matches) != 1:
        raise ValueError(f'CRD does not serve exactly one {version} version')
    source = matches[0]['schema']['openAPIV3Schema']
    schema = strict(source)
    schema['$comment'] = (f"Generated by ci/crd_schema.py from {crd['metadata']['name']} {version}; "
                          'source sha256 ' + hashlib.sha256(json.dumps(source, sort_keys=True).encode()).hexdigest())
    name = f"crd-{spec['group']}-{spec['names']['kind'].lower()}-{version}.json"
    return name, schema


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('crd', type=Path)
    parser.add_argument('version')
    args = parser.parse_args()
    name, schema = convert(json.loads(args.crd.read_text()), args.version)
    target = Path(__file__).with_name(name)
    target.write_text(json.dumps(schema, sort_keys=True, separators=(',', ':')) + '\n')
    print(f'{target.name}: {target.stat().st_size} bytes')


if __name__ == '__main__':
    main()
